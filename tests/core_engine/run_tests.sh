#!/bin/bash
# Run core-engine tests (issue #241): session lifecycle through
# packet_session.c's session manager and the memory.c arena allocator.
# Part 2 (issue #242) adds the classification utilities: hostname matching
# (doted-name trie + linear suffix scan), the CIDR attribution trees and the
# memoized packet-offset cache.
#
# The suite source-compiles packet_processing.c and the objects it needs from
# src/mmt_core (packet_registry*, packet_pipeline, packet_session,
# packet_stats, memory, hashmap, mmt_data, mmt_inet_ntop, proto_meta,
# plugins_engine, extraction_lib, mmt_init, dpi_profiles) plus
# hash_utils.c, so gcov records them under --coverage and ASan/UBSan
# instrument them under SANITIZE=*.
#
# -Wl,--wrap=malloc/--wrap=calloc route the library's libc allocations through
# the budget counters in test_core_engine.c — since issue #539 that covers
# hash_utils.c too (its last operator-new sites, and the interposer that
# failed them, are gone with the C++ TU).
#
# Issue #545: test_mmt_log compiles src/mmt_core/src/mmt_log.c, the SDK
# logger, with its unit test (levels, MMT_DPI_LOG_LEVEL, stderr-only output,
# per-site rate limit, counters under concurrent writers — under TSan in the
# SANITIZE=tsan mode).
#
# Issue #554: test_ip_session_ids includes
# src/mmt_tcpip/lib/protocols/ip_session_id_management.c (the IP session
# store: interned address ids, get_session(), free_session_data() and the
# per-protocol session counters) and links the suite's hash_utils.o and
# memory.o. -Wl,--wrap on malloc, mmt_malloc, mmt_free, insert_key_value and
# insert_session_into_protocol_context lets it fail each allocation and insert
# get_session() makes and check the rollback releases what it created.
#
# Issue #566: check_hostname_table.sh fails the suite when the committed
# hostname-suffix .inc is not what tools/gen-hostname-table.py generates from
# data/hostnames.txt, and checks the generator rejects malformed data.
#
# Issue #557: test_ip_range_lpm checks the compiled-in IPv4 attribution
# lookup (a const interval array generated by tools/gen-ip-range-table.py
# from data/ip_ranges.txt) against the former per-prefix AVL forest over every
# table prefix, random pairs and external rules, plus the per-flow verdict
# memo; check_ip_range_table.sh is the generator's drift and rejection gate.
#
# Issue #525: the same library objects (plus mmt_attr_sprintf_compat.c and,
# since #533, mmt_utils.c) also
# link test_api_contracts — the public-API contract table, one entry per
# MMTAPI function, linked without the allocator wraps. After it passes,
# tools/ci/check-api-contracts.sh fails the suite when a declared MMTAPI
# function has no entry (or an entry is stale, duplicated or an unlisted
# waiver).
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

CORE_SRC="$PROJECT_DIR/src/mmt_core/src"
CORE_PRIVATE_INC="$PROJECT_DIR/src/mmt_core/private_include"
CORE_PUBLIC_INC="$PROJECT_DIR/src/mmt_core/public_include"

CC="${CC:-gcc}"
read -r -a extra_cflags <<< "${EXTRA_CFLAGS:-}"

INCS=(-I"$CORE_PRIVATE_INC" -I"$CORE_PUBLIC_INC" -I"$PROJECT_DIR/src/mmt_tcpip/lib")

# Issue #546: the classifier typedef returns mmt_classify_verdict_t in C and
# keeps its int view in C++; an int-returning classifier must still register
# from both languages, through the public headers alone, without a warning.
echo "Compiling the classifier-typedef probe (C and C++)..."
"$CC" -std=gnu17 -Wall -Wextra -Werror -c -I"$CORE_PUBLIC_INC" \
    "$SCRIPT_DIR/verdict_typedef_probe.c" -o /dev/null
"${CXX:-g++}" -x c++ -std=c++11 -Wall -Wextra -Werror -fsyntax-only -I"$CORE_PUBLIC_INC" \
    "$SCRIPT_DIR/verdict_typedef_probe.c"

echo "Compiling core-engine tests..."

C_SOURCES="packet_processing.c packet_registry.c packet_registry_classify.c \
packet_registry_handler.c packet_registry_attr.c packet_pipeline.c \
packet_session.c packet_stats.c memory.c \
hashmap.c mmt_data.c mmt_inet_ntop.c \
proto_meta.c plugins_engine.c extraction_lib.c mmt_init.c \
dpi_profiles.c hash_utils.c"

# lib_objects: the library under test, shared by both binaries (one set of
# .o files, so --coverage counters from both runs merge).
lib_objects=()
for src in $C_SOURCES; do
    obj="$SCRIPT_DIR/$(basename "$src" .c).o"
    "$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
        -c "$CORE_SRC/$src" -o "$obj"
    lib_objects+=("$obj")
done

# Issue #242: the classification-utility unit under test lives in
# src/mmt_tcpip/lib. Compile it and its avltree dependency here; the unit's
# mmt_common_internal_include.h pulls protocols/rtp.h, which needs the
# fuzz-engine include dir for mmt_quality_estimation_utilities.h.
# -Wno-missing-field-initializers keeps the generated 3-field table entries
# quiet under -Wextra.
TCPIP_SRC="$PROJECT_DIR/src/mmt_tcpip/lib"
for src in avltree.c mmt_tcpip_classif_utils.c; do
    obj="$SCRIPT_DIR/$(basename "$src" .c).o"
    "$CC" "${extra_cflags[@]}" -Wall -Wextra -Wno-missing-field-initializers \
        -std=gnu11 "${INCS[@]}" -I"$PROJECT_DIR/src/mmt_fuzz_engine" \
        -c "$TCPIP_SRC/$src" -o "$obj"
    lib_objects+=("$obj")
done

objects=("${lib_objects[@]}")
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
    -c "$SCRIPT_DIR/test_core_engine.c" -o "$SCRIPT_DIR/test_core_engine.o"
objects+=("$SCRIPT_DIR/test_core_engine.o")

"$CC" "${extra_cflags[@]}" -Wl,--wrap=malloc -Wl,--wrap=calloc -Wl,--wrap=realloc \
    -o "$SCRIPT_DIR/test_core_engine" "${objects[@]}" -lm -lpthread -ldl

# Issue #557: the IP-range differential test — the interval-array lookup
# against the former per-prefix AVL forest, rebuilt from the table's prefixes,
# which tools/gen-ip-range-table.py writes from data/ip_ranges.txt.
GEN_DIR="$(mktemp -d)"
python3 "$PROJECT_DIR/tools/gen-ip-range-table.py" --check \
    --prefix-table "$GEN_DIR/ip_range_prefixes.inc" > /dev/null
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" -I"$GEN_DIR" \
    -c "$SCRIPT_DIR/test_ip_range_lpm.c" -o "$SCRIPT_DIR/test_ip_range_lpm.o"
rm -rf -- "$GEN_DIR"
"$CC" "${extra_cflags[@]}" -o "$SCRIPT_DIR/test_ip_range_lpm" "${lib_objects[@]}" \
    "$SCRIPT_DIR/test_ip_range_lpm.o" -lm -lpthread -ldl

# Issue #525: the public-API contract binary — library objects only, no wraps.
# Issue #533 adds mmt_utils.c: its string/hex utilities are MMTAPI now.
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
    -c "$CORE_SRC/mmt_attr_sprintf_compat.c" -o "$SCRIPT_DIR/mmt_attr_sprintf_compat.o"
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
    -c "$CORE_SRC/mmt_utils.c" -o "$SCRIPT_DIR/mmt_utils.o"
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
    -c "$SCRIPT_DIR/test_api_contracts.c" -o "$SCRIPT_DIR/test_api_contracts.o"
"$CC" "${extra_cflags[@]}" -o "$SCRIPT_DIR/test_api_contracts" "${lib_objects[@]}" \
    "$SCRIPT_DIR/mmt_attr_sprintf_compat.o" "$SCRIPT_DIR/mmt_utils.o" \
    "$SCRIPT_DIR/test_api_contracts.o" -lm -lpthread -ldl

# Issue #545: the logger and its unit test.
"$CC" "${extra_cflags[@]}" -Wall -Wextra -std=gnu11 "${INCS[@]}" \
    -o "$SCRIPT_DIR/test_mmt_log" "$CORE_SRC/mmt_log.c" "$SCRIPT_DIR/test_mmt_log.c" \
    -lpthread

# Issue #554: the IP session store, with link-time allocation/insert faults.
"$CC" "${extra_cflags[@]}" -Wall -Wextra -Wno-unused-parameter -std=gnu11 "${INCS[@]}" \
    -I"$PROJECT_DIR/src/mmt_tcpip/include" -I"$PROJECT_DIR/src/mmt_fuzz_engine" \
    -c "$SCRIPT_DIR/test_ip_session_ids.c" -o "$SCRIPT_DIR/test_ip_session_ids.o"
"$CC" "${extra_cflags[@]}" -Wl,--wrap=malloc -Wl,--wrap=mmt_malloc -Wl,--wrap=mmt_free \
    -Wl,--wrap=insert_key_value -Wl,--wrap=insert_session_into_protocol_context \
    -o "$SCRIPT_DIR/test_ip_session_ids" "$SCRIPT_DIR/test_ip_session_ids.o" \
    "$SCRIPT_DIR/hash_utils.o" "$SCRIPT_DIR/memory.o" -lpthread

# Point the plugin loader at an empty scratch directory for every binary
# that calls init_extraction(): the source-compiled
# plugins_engine.c defaults to /opt/mmt/plugins, whose plugins (if a host
# install exists) cannot link against this static test binary, and a failed
# plugin now fails init_extraction() (issue #503). The engine prints verbose
# DEBUG lines; keep them in a log and only surface it when the suite fails.
echo "Running core-engine tests..."
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir "$WORK/plugins"
export MMT_DPI_PLUGINS_DIR="$WORK/plugins"
if ( cd "$WORK" && "$SCRIPT_DIR/test_core_engine" > "$WORK/core_engine.log" 2>&1 ); then
    echo "Core-engine tests: PASSED"
else
    cat "$WORK/core_engine.log"
    echo "Core-engine tests: FAILED"
    exit 1
fi

echo "Running hostname-table generator checks (issue #566)..."
if bash "$SCRIPT_DIR/check_hostname_table.sh"; then
    echo "Hostname-table tests: PASSED"
else
    echo "Hostname-table tests: FAILED"
    exit 1
fi

echo "Running IP-range LPM differential test (issue #557)..."
if ( cd "$WORK" && "$SCRIPT_DIR/test_ip_range_lpm" "$WORK/ip_range_lpm_rules.txt" \
        > "$WORK/ip_range_lpm.log" 2>&1 ); then
    tail -n 1 "$WORK/ip_range_lpm.log"
else
    cat "$WORK/ip_range_lpm.log"
    echo "IP-range LPM tests: FAILED"
    exit 1
fi

echo "Running IP-range table generator checks (issue #557)..."
if bash "$SCRIPT_DIR/check_ip_range_table.sh"; then
    echo "IP-range table tests: PASSED"
else
    echo "IP-range table tests: FAILED"
    exit 1
fi

echo "Running public-API contract tests..."
if ( cd "$WORK" && "$SCRIPT_DIR/test_api_contracts" > "$WORK/api_contracts.log" 2>&1 ); then
    tail -n 1 "$WORK/api_contracts.log"
else
    cat "$WORK/api_contracts.log"
    echo "Public-API contract tests: FAILED"
    exit 1
fi
bash "$PROJECT_DIR/tools/ci/check-public-decls.sh" --list > "$WORK/api_decls.txt"
"$SCRIPT_DIR/test_api_contracts" --list > "$WORK/api_contracts.txt"
if bash "$PROJECT_DIR/tools/ci/check-api-contracts.sh" --decls "$WORK/api_decls.txt" \
        --contracts "$WORK/api_contracts.txt" \
        --waivers "$SCRIPT_DIR/api-contract-waivers.txt"; then
    echo "Public-API contract tests: PASSED"
else
    echo "Public-API contract tests: FAILED"
    exit 1
fi

echo "Running logger tests (issue #545)..."
if ( cd "$WORK" && "$SCRIPT_DIR/test_mmt_log" > "$WORK/mmt_log.log" 2>&1 ); then
    tail -n 1 "$WORK/mmt_log.log"
    echo "Logger tests: PASSED"
else
    cat "$WORK/mmt_log.log"
    echo "Logger tests: FAILED"
    exit 1
fi

echo "Running IP session store tests (issue #554)..."
if ( cd "$WORK" && "$SCRIPT_DIR/test_ip_session_ids" > "$WORK/ip_session_ids.log" 2>&1 ); then
    tail -n 1 "$WORK/ip_session_ids.log"
    echo "IP session store tests: PASSED"
else
    cat "$WORK/ip_session_ids.log"
    echo "IP session store tests: FAILED"
    exit 1
fi
