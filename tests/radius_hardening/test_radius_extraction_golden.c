/*
 * test_radius_extraction_golden.c — issue #543: every RADIUS attribute
 * extracts byte-for-byte what it did before the extractors became
 * table-driven.
 *
 * src/mmt_tcpip/lib/protocols/proto_radius.c used to hold one extraction
 * function per attribute (183 of them); #543 replaced them with a
 * descriptor table and a few generic extractors. This program registers
 * EVERY RADIUS attribute (RADIUS_CODE .. RADIUS_AVP240), feeds crafted
 * Ethernet/IPv4/UDP/RADIUS frames through the installed SDK
 * (mmt_init_handler + packet_process) and folds, per attribute, everything
 * get_attribute_extracted_data() reports into a 64-bit FNV-1a digest:
 *
 *   - for each packet: the frame and packet numbers and whether the
 *     attribute was reported;
 *   - when reported: the WHOLE attribute buffer (get_data_size_by_data_type
 *     bytes — 68 for MMT_BINARY_DATA, so the clamp, the NUL terminator and
 *     the bytes past the value all count), or, for MMT_DATA_POINTER
 *     attributes, the TLV's offset in the packet and its type/len/value
 *     bytes.
 *
 * It prints one line per attribute (`<id> <name> <reported> <digest>`);
 * run_tests.sh compares the output with radius_extraction.golden, which
 * was generated by this program against the pre-#543 parser. A changed
 * line names the attribute whose extraction moved.
 * RADIUS_GOLDEN_DUMP=1 also prints every reported buffer in hex.
 *
 * The frames carry every packet attribute type 0..255 (26 excepted) and
 * every 3GPP vendor sub-attribute 0..27 at value lengths around each
 * extractor's guard (0-8, 14-18 for the IPv6/interface-id copies, 61-66
 * for the 64-byte clamps, 200), an attribute-free frame, repeated types
 * (the last occurrence wins) and per-type mixed lengths. Value bytes
 * depend on the type and position, so reading the wrong TLV changes the
 * digest. Each frame is its own session and is sent twice; frames are
 * exactly-sized heap copies.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <inttypes.h>

#include <pcap.h>            /* DLT_EN10MB */

#include "mmt_core.h"
#include "tcpip/mmt_tcpip.h"
#include "tcpip/mmt_tcpip_attributes.h" /* RADIUS_* attribute ids */

#define N_ATTRS   RADIUS_ATTRIBUTES_NB  /* ids 1 .. RADIUS_AVP240 */
#define SENDS     2
#define VENDOR_3GPP 10415u
#define N_3GPP_SUBTYPES 28              /* 0 .. VENDOR_3GPP_MAX_TLV_TYPE */

static uint64_t g_digest[N_ATTRS + 1];
static unsigned g_reported[N_ATTRS + 1];
static long     g_type[N_ATTRS + 1];
static unsigned g_frame, g_pkt;
static int      g_radius_seen;
static int      g_dump;

static void fnv(uint64_t *h, const void *p, size_t n) {
    const uint8_t *b = (const uint8_t *) p;
    for (size_t i = 0; i < n; i++) {
        *h ^= b[i];
        *h *= 0x100000001b3ULL;
    }
}

static void dump(uint32_t id, const char *what, const uint8_t *b, size_t n) {
    printf("  frame %u pkt %u attr %u %s:", g_frame, g_pkt, id, what);
    for (size_t i = 0; i < n; i++) printf("%02x", b[i]);
    printf("\n");
}

static int packet_handler(const ipacket_t *ipacket, void *user_args) {
    (void) user_args;
    if (ipacket->proto_hierarchy != NULL) {
        for (int i = 0; i < ipacket->proto_hierarchy->len; i++)
            if (ipacket->proto_hierarchy->proto_path[i] == PROTO_RADIUS)
                g_radius_seen++;
    }
    for (uint32_t id = 1; id <= N_ATTRS; id++) {
        const uint8_t *d = (const uint8_t *)
            get_attribute_extracted_data(ipacket, PROTO_RADIUS, id);
        uint8_t present = d != NULL;
        fnv(&g_digest[id], &g_frame, sizeof(g_frame));
        fnv(&g_digest[id], &g_pkt, sizeof(g_pkt));
        fnv(&g_digest[id], &present, 1);
        if (!present) continue;
        g_reported[id]++;
        if (g_type[id] == MMT_DATA_POINTER) {
            /* d is the TLV itself: its place in the packet, then its bytes
             * (the parser stored it only with len >= 2 inside caplen). */
            int64_t off = (int64_t) (d - ipacket->data);
            fnv(&g_digest[id], &off, sizeof(off));
            fnv(&g_digest[id], d, d[1]);
            if (g_dump) dump(id, "tlv", d, d[1]);
        } else {
            uint32_t size = get_data_size_by_data_type((uint32_t) g_type[id]);
            fnv(&g_digest[id], d, size);
            if (g_dump) dump(id, "buf", d, size);
        }
    }
    return 0;
}

/* ---- frame builder ------------------------------------------------------ */

#define MAX_ATTR_BYTES 65000
static uint8_t  g_attr_bytes[MAX_ATTR_BYTES];
static unsigned g_attr_len;

static void put_be16(uint8_t *p, uint16_t v) { p[0] = v >> 8; p[1] = v & 0xff; }

static void raw(const uint8_t *b, unsigned n) {
    if (g_attr_len + n > sizeof(g_attr_bytes)) { fprintf(stderr, "attr overflow\n"); exit(2); }
    memcpy(g_attr_bytes + g_attr_len, b, n);
    g_attr_len += n;
}

/* Packet attribute `type` with an `n`-byte value; `salt` varies the bytes. */
static void tlv(uint8_t type, unsigned n, unsigned salt) {
    uint8_t v[253];
    for (unsigned j = 0; j < n; j++) v[j] = (uint8_t) (type * 29u + j * 13u + salt * 7u + 1u);
    uint8_t h[2] = { type, (uint8_t) (2 + n) };
    raw(h, 2);
    raw(v, n);
}

/* 3GPP vendor-specific attribute (type 26) holding sub-attribute `sub`
 * with an `n`-byte value. */
static void vsa(uint8_t sub, unsigned n, unsigned salt) {
    uint8_t v[255];
    v[0] = 26; v[1] = (uint8_t) (8 + n);
    v[2] = 0; v[3] = 0; v[4] = (uint8_t) (VENDOR_3GPP >> 8); v[5] = (uint8_t) VENDOR_3GPP;
    v[6] = sub; v[7] = (uint8_t) (2 + n);
    for (unsigned j = 0; j < n; j++) v[8 + j] = (uint8_t) (sub * 41u + j * 11u + salt * 3u + 0x80u);
    raw(v, 8 + n);
}

static mmt_handler_t *g_h;
static uint16_t g_sport = 42000;

/* Wraps the attributes in an Access-Request and Ethernet/IPv4/UDP and
 * sends it twice on a fresh session. */
static void send_frame(void) {
    unsigned rlen = 20 + g_attr_len;
    unsigned len = 42 + rlen;
    if (20 + 8 + rlen > 0xffff) { fprintf(stderr, "frame too large\n"); exit(2); }
    uint8_t *pkt = calloc(1, len);
    if (!pkt) { perror("calloc"); exit(2); }
    uint8_t *r = pkt + 42;
    r[0] = 1;                                /* Access-Request */
    r[1] = 0x5a;
    put_be16(r + 2, (uint16_t) rlen);        /* == UDP payload length */
    for (int i = 0; i < 16; i++) r[4 + i] = (uint8_t) (0xa0 + i * 3 + g_frame);
    memcpy(r + 20, g_attr_bytes, g_attr_len);

    static const uint8_t dst[6] = {0x00,0x11,0x22,0x33,0x44,0x55};
    static const uint8_t src[6] = {0x66,0x77,0x88,0x99,0xaa,0xbb};
    memcpy(pkt, dst, 6); memcpy(pkt + 6, src, 6); put_be16(pkt + 12, 0x0800);
    uint8_t *ip = pkt + 14;
    ip[0] = 0x45; put_be16(ip + 2, (uint16_t) (20 + 8 + rlen));
    ip[8] = 64; ip[9] = 17;
    ip[12] = 10; ip[15] = 1; ip[16] = 10; ip[19] = 2;
    uint8_t *u = pkt + 34;
    put_be16(u, g_sport++); put_be16(u + 2, 1812);
    put_be16(u + 4, (uint16_t) (8 + rlen)); put_be16(u + 6, 0);

    for (g_pkt = 0; g_pkt < SENDS; g_pkt++) {
        uint8_t *data = malloc(len);
        if (!data) { perror("malloc"); exit(2); }
        memcpy(data, pkt, len);
        struct pkthdr hdr;
        memset(&hdr, 0, sizeof(hdr));
        hdr.ts.tv_sec = 1 + g_pkt;
        hdr.caplen = len;
        hdr.len = len;
        packet_process(g_h, &hdr, data);
        free(data);
    }
    free(pkt);
    g_frame++;
    g_attr_len = 0;
}

/* Every packet type but 26, then every 3GPP sub-attribute, at value
 * length n (sub-attributes capped to fit the one-byte VSA length). */
static void frame_all_types(unsigned n) {
    for (unsigned t = 0; t <= 255; t++)
        if (t != 26) tlv((uint8_t) t, n, n);
    for (unsigned s = 0; s < N_3GPP_SUBTYPES; s++)
        vsa((uint8_t) s, n > 247 ? 247 : n, n);
    send_frame();
}

int main(void) {
    char errbuf[1024];
    setvbuf(stdout, NULL, _IOLBF, 0);
    g_dump = getenv("RADIUS_GOLDEN_DUMP") != NULL;
    if (!init_extraction()) {
        fprintf(stderr, "init_extraction failed\n");
        return 2;
    }
    g_h = mmt_init_handler(DLT_EN10MB, 0, errbuf);
    if (g_h == NULL) {
        fprintf(stderr, "mmt_init_handler failed: %s\n", errbuf);
        close_extraction();
        return 2;
    }
    register_packet_handler(g_h, 1, packet_handler, NULL);
    for (uint32_t id = 1; id <= N_ATTRS; id++) {
        g_digest[id] = 0xcbf29ce484222325ULL;
        g_type[id] = get_attribute_data_type(PROTO_RADIUS, id);
        if (register_extraction_attribute(g_h, PROTO_RADIUS, id) != true) {
            fprintf(stderr, "register_extraction_attribute(%u) failed\n", id);
            mmt_close_handler(g_h);
            close_extraction();
            return 2;
        }
    }

    /* 1. no attributes at all */
    send_frame();

    /* 2. every type at lengths around the extractors' guards */
    static const unsigned lens[] = { 0, 1, 2, 3, 4, 5, 6, 7, 8, 14, 15, 16, 17, 18,
                                     61, 62, 63, 64, 65, 66, 200 };
    for (size_t i = 0; i < sizeof(lens) / sizeof(lens[0]); i++)
        frame_all_types(lens[i]);

    /* 3. repeated types: the last occurrence is the one reported */
    tlv(1, 5, 1); tlv(4, 4, 1); tlv(30, 9, 1); vsa(1, 15, 1); vsa(6, 4, 1);
    tlv(1, 9, 2); tlv(4, 4, 2); tlv(30, 3, 2); vsa(1, 7, 2);  vsa(6, 4, 2);
    send_frame();

    /* 4. mixed lengths per type */
    for (unsigned t = 0; t <= 255; t++)
        if (t != 26) tlv((uint8_t) t, (t * 7u) % 71u, 3);
    for (unsigned s = 0; s < N_3GPP_SUBTYPES; s++)
        vsa((uint8_t) s, (s * 13u) % 70u, 3);
    send_frame();

    if (g_radius_seen != (int) (g_frame * SENDS)) {
        fprintf(stderr, "only %d of %u packets were classified as RADIUS\n",
                g_radius_seen, g_frame * SENDS);
        mmt_close_handler(g_h);
        close_extraction();
        return 1;
    }
    printf("# issue #543: RADIUS extraction digests over %u frames x %d sends\n", g_frame, SENDS);
    printf("# <attribute id> <name> <packets reporting it> <FNV-1a 64 digest>\n");
    for (uint32_t id = 1; id <= N_ATTRS; id++) {
        const char *name = get_attribute_name_by_protocol_and_attribute_ids(PROTO_RADIUS, id);
        printf("%u %s %u %016" PRIx64 "\n", id, name ? name : "?", g_reported[id], g_digest[id]);
    }
    mmt_close_handler(g_h);
    close_extraction();
    return 0;
}
